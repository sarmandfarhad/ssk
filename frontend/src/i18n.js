export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(readLang);

  useEffect(() => {
    const meta = LANGS[lang] || LANGS.EN;
    document.documentElement.lang = meta.htmlLang;
    document.documentElement.dir = meta.dir;
    document.body.classList.toggle("is-rtl", meta.dir === "rtl");
  }, [lang]);

  const setLang = useCallback((next) => {
    const value = LANGS[next] ? next : "EN";
    setLangState(value);
    try {
      const prefs = JSON.parse(localStorage.getItem(PREFS_KEY) || "{}");
      localStorage.setItem(PREFS_KEY, JSON.stringify({ ...prefs, language: value }));
    } catch (error) {
      localStorage.setItem(PREFS_KEY, JSON.stringify({ language: value }));
    }
  }, []);

  const t = useCallback((key, vars) => translate(lang, key, vars), [lang]);
  const label = useCallback((value) => labelOf(lang, value), [lang]);
  const meta = LANGS[lang] || LANGS.EN;

  const value = useMemo(
    () => ({ lang, setLang, t, label, dir: meta.dir, meta }),
    [lang, setLang, t, label, meta]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error("useI18n must be used inside LanguageProvider");
  }
  return ctx;
}

export function LanguageSelect({ className }) {
  const { lang, setLang } = useI18n();
  return (
    <select className={className || "lang-switch"} value={lang} onChange={(event) => setLang(event.target.value)} aria-label="Language">
      <option value="EN">EN</option>
      <option value="KU">کوردی</option>
      <option value="AR">عربي</option>
    </select>
  );
}
